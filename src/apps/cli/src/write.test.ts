import {
  existsSync,
  mkdirSync,
  readFileSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { seed, zz, type Seeded } from "./test/seed.js";

let s: Seeded;
beforeEach(() => {
  s = seed();
});
afterEach(() => s.cleanup());

const agents = () => join(s.repo, "AGENTS.md");
const write = (args: string[] = [], cwd = s.repo) =>
  zz(["write", ...args, "--json"], { cwd, home: s.home });
const status = async (args: string[] = []) => {
  const r = await write(args);
  return { code: r.code, body: JSON.parse(r.stdout) };
};
const persona = () => join(s.repo, ".donn/persona.yaml");

describe("donn write", () => {
  it("writes the project persona's block and keeps it current", async () => {
    expect((await status()).body).toMatchObject({
      path: agents(),
      status: "created",
    });
    const text = readFileSync(agents(), "utf8");
    expect(text).toContain("<!-- donn:begin");
    expect(text).toContain("Generated by donn from project/persona");
    expect((await status()).body.status).toBe("unchanged");
    expect(await status(["--check"])).toMatchObject({
      code: 0,
      body: { status: "unchanged" },
    });
  });

  it("fails --check when the persona changes, writing nothing", async () => {
    await write();
    const before = readFileSync(agents(), "utf8");
    const file = readFileSync(persona(), "utf8");
    writeFileSync(
      persona(),
      file.includes("instructions:")
        ? file.replace(
            "instructions:",
            "instructions:\n  - { id: added-note, inline: A new rule. }",
          )
        : `${file}instructions:\n  - { id: added-note, inline: A new rule. }\n`,
    );
    expect(await status(["--check"])).toMatchObject({
      code: 1,
      body: { status: "stale" },
    });
    expect(readFileSync(agents(), "utf8")).toBe(before);
  });

  it("removes the block", async () => {
    await write();
    expect((await status(["--remove"])).body.status).toBe("removed");
    expect(existsSync(agents())).toBe(false);
  });

  it("ignores the user overlay", async () => {
    writeFileSync(
      join(s.home, "overrides.yaml"),
      [
        "apiVersion: donn/v0",
        "kind: PersonaOverlay",
        "instructions:",
        "  - { id: mine, inline: ZZ-USER-ONLY-RULE }",
        "",
      ].join("\n"),
    );
    await write();
    expect(readFileSync(agents(), "utf8")).not.toContain("ZZ-USER-ONLY-RULE");
  });

  it("refuses a project persona that extends a user persona", async () => {
    mkdirSync(join(s.home, "personas"), { recursive: true });
    writeFileSync(
      join(s.home, "personas/mine.yaml"),
      "apiVersion: donn/v0\nkind: Persona\nmetadata: { name: mine }\n",
    );
    writeFileSync(
      persona(),
      "apiVersion: donn/v0\nkind: Persona\nmetadata: { name: repo }\nextends: [user/mine]\n",
    );
    const r = await write();
    expect(r.code).toBe(1);
    expect(JSON.parse(r.stdout).error.code).toBe("user-layer-in-shared-file");
  });

  it("needs a project persona", async () => {
    const r = await write([], s.root);
    expect(JSON.parse(r.stdout).error.code).toBe("no-project-persona");
  });

  it("refuses a harness that launches a program", async () => {
    const r = await write(["--harness", "claude-code"]);
    expect(JSON.parse(r.stdout).error.code).toBe("not-a-file-harness");
  });

  it("writes the repo root's AGENTS.md from a subdirectory", async () => {
    mkdirSync(join(s.repo, "src/deep"), { recursive: true });
    const r = await write([], join(s.repo, "src/deep"));
    expect(JSON.parse(r.stdout).path).toBe(agents());
  });

  it("reports malformed markers with their line", async () => {
    writeFileSync(agents(), "# Rules\n<!-- donn:begin -->\nno end\n");
    const r = await write();
    expect(JSON.parse(r.stdout).error).toMatchObject({
      code: "agents-md-markers",
      line: 2,
    });
  });

  it("previews the block with compile --dry-run", async () => {
    const r = await zz(
      ["compile", "--harness", "agents-md", "--dry-run", "--no-overlay"],
      { cwd: s.repo, home: s.home },
    );
    expect(r.code, r.stderr).toBe(0);
    expect(r.stdout).toContain("AGENTS.md.block");
    expect(r.stdout).toContain("overlay AGENTS.md block donn");
  });

  it("refuses an overlay without a block, so it never replaces a file it does not own", async () => {
    const adapter = join(
      import.meta.dirname,
      "test/plugins/whole-file-adapter",
    );
    writeFileSync(
      join(s.home, "config.yaml"),
      `personas: ${s.personas}\nadapters: [${adapter}]\n`,
    );
    mkdirSync(join(s.repo, ".github"), { recursive: true });
    writeFileSync(
      join(s.repo, ".github/copilot-instructions.md"),
      "hand-written\n",
    );
    const r = await write(["--harness", "whole-file"]);
    expect(JSON.parse(r.stdout).error.code).toBe("overlay-needs-block");
    expect(
      readFileSync(join(s.repo, ".github/copilot-instructions.md"), "utf8"),
    ).toBe("hand-written\n");
  });

  it("refuses an instruction file that is the repo's own AGENTS.md", async () => {
    writeFileSync(agents(), "# Team rules\n");
    mkdirSync(join(s.repo, ".donn/instructions"), { recursive: true });
    symlinkSync(
      "../../AGENTS.md",
      join(s.repo, ".donn/instructions/agents.md"),
    );
    writeFileSync(
      persona(),
      [
        "apiVersion: donn/v0",
        "kind: Persona",
        "metadata: { name: repo }",
        "extends: [org/base]",
        "instructions:",
        "  - { id: team, file: ./instructions/agents.md }",
        "",
      ].join("\n"),
    );
    await write();
    const second = await write();
    expect(second.code).toBe(1);
    expect(JSON.parse(second.stdout).error.message).toContain(
      "holds the generated donn block",
    );
    expect(readFileSync(agents(), "utf8").match(/donn:end/g)).toHaveLength(1);
  });
});
