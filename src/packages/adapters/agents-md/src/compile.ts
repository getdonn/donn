import {
  AdapterInputError,
  annotateLocks,
  assertIrVersion,
  requiredEntries,
  type CompileInput,
  type CompileOutput,
  type HarnessAdapter,
  type ReportEntry,
} from "@getdonn/adapter-sdk";
import { capabilities } from "./capabilities.js";

// The text of the donn block in a repo's AGENTS.md: a header naming the persona, its
// instructions, knowledge pointers, and its permissions as guidance. The executor merges it
// between markers. See docs/planning/11-agents-md.md, section 1.

export const BLOCK_FILE = "AGENTS.md.block";
const SIZE_LIMIT = 24 * 1024;

function rules(title: string, list: readonly string[]): string[] {
  return list.length === 0
    ? []
    : [`${title}\n${list.map((r) => `- ${r}`).join("\n")}`];
}

export function compile(
  input: CompileInput,
  self: HarnessAdapter,
): CompileOutput {
  const { ir, personaId, texts } = input;
  assertIrVersion(self, ir);
  const parts = [
    `Generated by donn from ${personaId} (${ir.layers.join(" → ")}); edit the persona, not this block.`,
    ...ir.instructions.map((fragment) => {
      if ("inline" in fragment) return fragment.inline.trimEnd();
      const text = texts[fragment.file];
      if (text === undefined) {
        throw new AdapterInputError(
          `no text supplied for instruction file ${fragment.file}`,
        );
      }
      // An instruction file linked to the repo's AGENTS.md would inline the block into itself.
      if (/^\s*<!-- donn:(begin|end)\b/m.test(text)) {
        throw new AdapterInputError(
          `instruction file ${fragment.file} holds the generated donn block (is it the repo's AGENTS.md?); point it at a file without the block`,
        );
      }
      return text.trimEnd();
    }),
  ];
  if (ir.knowledge.length > 0) {
    parts.push(
      `## Knowledge sources\n${ir.knowledge.map((k) => `- ${k.id}: ${k.source}`).join("\n")}`,
    );
  }
  const toolRules = [
    ...rules("Never run:", ir.permissions.deny),
    ...rules("Ask before:", ir.permissions.ask),
    ...rules("Allowed:", ir.permissions.allow),
  ];
  if (toolRules.length > 0)
    parts.push(["## Tool rules", ...toolRules].join("\n\n"));
  const content = `${parts.join("\n\n")}\n`;

  const entries: ReportEntry[] = requiredEntries(self.id, capabilities(), ir);
  if (ir.mcp.gateway !== undefined) {
    entries.push({
      path: "mcp.gateway",
      outcome: "dropped",
      reason: "AGENTS.md is plain text; use a harness adapter for MCP servers",
    });
  }
  const bytes = Buffer.byteLength(content);
  if (bytes > SIZE_LIMIT) {
    entries.push({
      path: "instructions",
      outcome: "advisory",
      reason: `the block is ${bytes} bytes, over 24 KiB; Codex reads only part of a large AGENTS.md`,
    });
  }
  return {
    files: { [BLOCK_FILE]: { content } },
    secretEnv: {},
    report: annotateLocks(
      { adapter: self.id, irVersion: ir.irVersion, entries },
      ir,
    ),
  };
}
