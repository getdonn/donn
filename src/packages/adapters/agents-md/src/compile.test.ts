import {
  AdapterInputError,
  type CompileInput,
  type CompileOutput,
} from "@zzpersona/adapter-sdk";
import { corpus } from "@zzpersona/adapter-sdk/conformance";
import { describe, expect, it } from "vitest";
import adapter from "./index.js";

const entry = (name: string) => corpus.find((e) => e.name === name)!;
const input = (
  name: string,
  overrides: Partial<CompileInput> = {},
): CompileInput => {
  const { personaId, ir, texts } = entry(name);
  return {
    personaId,
    ir,
    texts,
    detection: { installed: true, version: "n/a", facts: {} },
    ...overrides,
  };
};
const block = (output: CompileOutput) => {
  const file = output.files["AGENTS.md.block"];
  if (!file || !("content" in file)) throw new Error("no block");
  return file.content;
};

describe("compile", () => {
  const full = adapter.compile(input("full"));
  const text = block(full);

  it("heads the block with the persona and its layers", () => {
    const { personaId, ir } = entry("full");
    expect(text.split("\n")[0]).toBe(
      `Generated by zzpersona from ${personaId} (${ir.layers.join(" → ")}); edit the persona, not this block.`,
    );
    expect(text.endsWith("\n")).toBe(true);
  });

  it("renders instructions in order, knowledge and tool rules", () => {
    const { ir, texts } = entry("full");
    let at = 0;
    for (const fragment of ir.instructions) {
      const body = (
        "inline" in fragment ? fragment.inline : texts[fragment.file]!
      ).trimEnd();
      const found = text.indexOf(body, at);
      expect(found, fragment.id).toBeGreaterThan(at - 1);
      at = found;
    }
    expect(text).toContain("## Knowledge sources");
    expect(text).toContain("## Tool rules");
    for (const rule of ir.permissions.deny) expect(text).toContain(`- ${rule}`);
    expect(text).toContain("Never run:");
  });

  it("reports what AGENTS.md cannot carry", () => {
    const outcome = (path: string) =>
      full.report.entries.find((e) => e.path.startsWith(path))?.outcome;
    const { ir } = entry("full");
    if (ir.skills.length) expect(outcome("skills[")).toBe("dropped");
    if (Object.keys(ir.mcp.servers).length)
      expect(outcome("mcp.servers.")).toBe("dropped");
    if (ir.permissions.deny.length)
      expect(outcome("permissions.deny[")).toBe("approximated");
    expect(
      full.report.entries.find((e) => e.path.startsWith("skills["))?.reason,
    ).toContain("AGENTS.md is plain text");
  });

  it("renders a header-only block", () => {
    const { ir } = entry("minimal");
    const out = adapter.compile(
      input("minimal", {
        ir: {
          ...ir,
          instructions: [],
          knowledge: [],
          permissions: { allow: [], deny: [], ask: [] },
        },
      }),
    );
    expect(block(out).split("\n").filter(Boolean)).toHaveLength(1);
  });

  it("warns past 24 KiB", () => {
    const { ir } = entry("minimal");
    const sized = (n: number) =>
      adapter.compile(
        input("minimal", {
          ir: {
            ...ir,
            knowledge: [],
            permissions: { allow: [], deny: [], ask: [] },
            instructions: [{ id: "big", inline: "x".repeat(n) }],
          },
        }),
      );
    const note = (out: CompileOutput) =>
      out.report.entries.some((e) => e.reason?.includes("24 KiB"));
    const header = Buffer.byteLength(block(sized(1))) - 1;
    expect(note(sized(24576 - header))).toBe(false);
    expect(note(sized(24577 - header))).toBe(true);
  });

  it("refuses an instruction file that is the generated AGENTS.md", () => {
    const { ir } = entry("minimal");
    const generated = [
      "# Repo rules",
      "<!-- zzpersona:begin — generated; edit the source, not this block -->",
      "old block",
      "<!-- zzpersona:end -->",
      "",
    ].join("\n");
    expect(() =>
      adapter.compile(
        input("minimal", {
          ir: {
            ...ir,
            instructions: [{ id: "agents", file: "project/AGENTS.md" }],
          },
          texts: { "project/AGENTS.md": generated },
        }),
      ),
    ).toThrow(/project\/AGENTS\.md holds the generated zzpersona block/);
  });

  it("throws AdapterInputError when an instruction file's text is missing", () => {
    expect(() => adapter.compile(input("full", { texts: {} }))).toThrow(
      AdapterInputError,
    );
  });
});

describe("activate", () => {
  it("returns one overlay step for the zzpersona block", () => {
    const output = adapter.compile(input("full"));
    const plan = adapter.activate({
      ir: entry("full").ir,
      output,
      buildDir: "/BUILD",
      detection: { installed: true, facts: {} },
      cwd: "/PROJECT",
      passthrough: [],
    });
    expect(plan.steps).toEqual([
      {
        kind: "overlay",
        path: "AGENTS.md",
        content: block(output),
        block: "zzpersona",
      },
    ]);
  });
});
