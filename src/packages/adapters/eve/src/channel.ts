// `agent/channels/eve.ts`: the route auth donn supplies for the local and self-host targets.
// eve fails closed under `eve start` and opens `localDev()` only under `eve dev`, so donn adds a
// bearer token of its own. See docs/planning/24-adapter-eve.md, section 5 (route auth) and
// spikes/eve-runner/FINDINGS-runtime.md (R1) for the shape eve 0.83.2 accepts.

export const CHANNEL_FILE = "agent/channels/eve.ts";
export const ROUTE_TOKEN_ENV = "DONN_ROUTE_TOKEN";

export const ROUTE_AUTH_FILE = "agent/lib/donn/route-auth.ts";

/** The token check, in its own module so a template's own channel can import it in one line. */
export const ROUTE_AUTH_TS = `// Generated by donn; edit the persona, not this file.
// The token is read per request, so \`eve build\` (which evaluates this module without the
// run-time environment) never needs it.
import { extractBearerToken, withAuthChallenges, type AuthFn } from "eve/channels/auth";

export const donnToken: AuthFn<Request> = withAuthChallenges(
  (request) => {
    const expected = process.env.${ROUTE_TOKEN_ENV};
    const token = extractBearerToken(request.headers.get("authorization"));
    if (!expected || !token || token !== expected) return null;
    return {
      attributes: {},
      authenticator: "donn",
      principalId: "donn-local",
      principalType: "service",
    };
  },
  [{ scheme: "Bearer" }],
);
`;

export const CHANNEL_TS = `// Generated by donn; edit the persona, not this file.
import { eveChannel } from "eve/channels/eve";
import { localDev } from "eve/channels/auth";
import { donnToken } from "../lib/donn/route-auth";

export default eveChannel({ auth: [donnToken, localDev()] });
`;
