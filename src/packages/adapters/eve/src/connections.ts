import type { FileEntry, ReportEntry } from "@getdonn/adapter-sdk";
import type { ResolvedPersona } from "@getdonn/spec";
import { propertyKey, SecretNames, valueExpression } from "./env.js";

// `agent/connections/donn-<name>.ts`. See docs/planning/24-adapter-eve.md, section 3.

const BEARER = /^Bearer (secret:\/\/\S+)$/;
const byName = ([a]: [string, unknown], [b]: [string, unknown]) =>
  a < b ? -1 : a > b ? 1 : 0;

type Server = ResolvedPersona["mcp"]["servers"][string];

/** The `description` the persona gives a server in `targets.eve.connections`, if any. */
function describedBy(ir: ResolvedPersona, server: string): string | undefined {
  const connections = (ir.targets.eve ?? {}).connections;
  const entry =
    typeof connections === "object" && connections !== null
      ? (connections as Record<string, unknown>)[server]
      : undefined;
  const description =
    typeof entry === "object" && entry !== null
      ? (entry as Record<string, unknown>).description
      : undefined;
  return typeof description === "string" && description.trim() !== ""
    ? description
    : undefined;
}

function connectionFile(
  server: string,
  definition: Extract<Server, { url: string }>,
  description: string,
  secrets: SecretNames,
): string {
  const fields: string[] = [
    `  url: ${valueExpression(definition.url, secrets)},`,
    `  description: ${JSON.stringify(description)},`,
  ];
  const headers: [string, string][] = [];
  for (const [key, value] of Object.entries(definition.headers ?? {}).sort(
    byName,
  )) {
    const bearer =
      key.toLowerCase() === "authorization" ? BEARER.exec(value) : null;
    if (bearer) {
      // eve's bearer form; the token is read when a request needs it.
      fields.push(
        `  auth: { getToken: async () => ({ token: process.env.${secrets.name(bearer[1]!)}! }) },`,
      );
    } else {
      headers.push([key, valueExpression(value, secrets)]);
    }
  }
  if (headers.length > 0) {
    fields.push(
      "  headers: {",
      ...headers.map(
        ([key, expression]) => `    ${propertyKey(key)}: ${expression},`,
      ),
      "  },",
    );
  }
  return [
    `// Generated by donn from MCP server "${server}"; edit the persona, not this file.`,
    'import { defineMcpClientConnection } from "eve/connections";',
    "",
    "export default defineMcpClientConnection({",
    ...fields,
    "});",
    "",
  ].join("\n");
}

/**
 * The url servers that got a name, as connection files, in server-name order (which is also the
 * secret numbering order), and the report entries for what was dropped or unrecognised.
 */
export function connectionFiles(
  ir: ResolvedPersona,
  personaId: string,
  names: ReadonlyMap<string, string>,
  secrets: SecretNames,
): { files: Record<string, FileEntry>; entries: ReportEntry[] } {
  const files: Record<string, FileEntry> = {};
  const entries: ReportEntry[] = [];
  for (const [server, definition] of Object.entries(ir.mcp.servers).sort(
    byName,
  )) {
    if ("command" in definition) {
      entries.push({
        path: `mcp.servers.${server}`,
        outcome: "dropped",
        reason: "eve connects to HTTP MCP and OpenAPI only",
      });
    } else if ("ref" in definition) {
      entries.push({
        path: `mcp.servers.${server}`,
        outcome: "dropped",
        reason:
          "gateway:// refs need gateway resolution, which is not available yet",
      });
    } else {
      const name = names.get(server);
      if (name === undefined) continue; // dropped by the name rule, already reported
      files[`agent/connections/${name}.ts`] = {
        content: connectionFile(
          server,
          definition,
          describedBy(ir, server) ??
            `${server} MCP server from persona ${personaId}`,
          secrets,
        ),
      };
    }
  }
  return { files, entries };
}

/** `targets.eve` keys this adapter does not read, as dropped entries. */
export function unknownTargetEntries(ir: ResolvedPersona): ReportEntry[] {
  const targets = ir.targets.eve ?? {};
  const entries: ReportEntry[] = [];
  for (const key of Object.keys(targets).sort()) {
    if (key === "contextWindow") continue;
    if (key !== "connections") {
      entries.push({
        path: `targets.eve.${key}`,
        outcome: "dropped",
        reason:
          "unknown targets.eve key; the eve adapter reads contextWindow and connections",
      });
      continue;
    }
    const connections = targets.connections;
    if (typeof connections !== "object" || connections === null) {
      entries.push({
        path: "targets.eve.connections",
        outcome: "dropped",
        reason:
          "targets.eve.connections must map a server name to { description }",
      });
      continue;
    }
    for (const [server, entry] of Object.entries(connections).sort(byName)) {
      const fields =
        typeof entry === "object" && entry !== null ? Object.keys(entry) : [];
      for (const field of fields.filter((f) => f !== "description")) {
        entries.push({
          path: `targets.eve.connections.${server}.${field}`,
          outcome: "dropped",
          reason: "unknown key; only description is read",
        });
      }
    }
  }
  return entries;
}
