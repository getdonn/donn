import { corpus } from "@getdonn/adapter-sdk/conformance";
import type { AgentCompileInput } from "@getdonn/adapter-sdk";
import type { ResolvedPersona } from "@getdonn/spec";
import { describe, expect, it } from "vitest";
import adapter from "./index.js";

const base = corpus.find((c) => c.name === "minimal")!.ir;

function input(
  patch: Partial<ResolvedPersona> = {},
  rest: Partial<AgentCompileInput> = {},
): AgentCompileInput {
  return {
    personaId: "team/solo",
    ir: {
      ...base,
      agents: {
        reviewer: {
          template: "eve:blank",
          target: "local",
          path: "agents/reviewer",
          env: {},
        },
      },
      ...patch,
    },
    agent: "reviewer",
    frameworkVersion: "0.83.2",
    texts: {},
    project: { hasSandbox: false, existing: [] },
    ...rest,
  };
}

const server = { url: "https://example.com/mcp" };

describe("instructions and knowledge", () => {
  it("renders them to instructions/donn.md in resolved order", () => {
    const out = adapter.compile(
      input(
        {
          instructions: [
            { id: "a", inline: "Be concise.\n" },
            { id: "b", file: "team/instructions/b.md" },
          ],
          knowledge: [
            { id: "wiki", source: "https://wiki.example.com" },
            { id: "db", source: "mcp://my_db" },
          ],
          mcp: { servers: { my_db: server } },
        },
        { texts: { "team/instructions/b.md": "From a file.\n" } },
      ),
    );
    const content = (out.files["agent/instructions/donn.md"] as any).content;
    expect(content).toBe(
      [
        "<!-- Generated by donn from team/solo; edit the persona, not this file. -->",
        "Be concise.",
        "From a file.",
        "## Knowledge sources\n- wiki: https://wiki.example.com\n- db: mcp://my_db (connection `donn-my-db`)",
      ].join("\n\n") + "\n",
    );
    expect(Object.keys(out.files)).toEqual(["agent/instructions/donn.md"]);
    expect(out.portability).toEqual([]);
  });

  it("reports knowledge as advisory and permissions, hooks, policy as dropped", () => {
    const out = adapter.compile(
      input({ knowledge: [{ id: "k", source: "https://x.example" }] }),
    );
    const byPath = Object.fromEntries(
      out.report.entries.map((e) => [e.path, e.outcome]),
    );
    expect(byPath["knowledge[k]"]).toBe("advisory");
    expect(byPath["permissions.allow[Read(./**)]"]).toBe("dropped");
  });

  it("throws when an instruction file has no text", () => {
    expect(() =>
      adapter.compile(
        input({ instructions: [{ id: "b", file: "team/b.md" }] }),
      ),
    ).toThrow(/no text supplied/);
  });

  it("refuses an agent the persona does not define", () => {
    expect(() => adapter.compile(input({}, { agent: "nope" }))).toThrow(
      /no agent "nope"/,
    );
  });
});

describe("skills", () => {
  const skill = { name: "review", source: "team/skills/review" };
  const withDescription =
    "---\nname: review\ndescription: Reviews code\n---\nBody";

  it("copies the skill directory whole to skills/donn-<name>/", () => {
    const out = adapter.compile(
      input(
        { skills: [skill] },
        { texts: { "team/skills/review/SKILL.md": withDescription } },
      ),
    );
    expect(out.files["agent/skills/donn-review"]).toEqual({
      copyFrom: "team/skills/review",
    });
    expect(
      out.report.entries.filter((e) => e.path.startsWith("skills")),
    ).toEqual([]);
  });

  it("compiles a skill with scripts for local, with the caveat in the report", () => {
    const out = adapter.compile(
      input(
        { skills: [skill] },
        {
          texts: {
            "team/skills/review/SKILL.md": withDescription,
            "team/skills/review/scripts/lint.sh": "echo",
          },
        },
      ),
    );
    expect(out.files["agent/skills/donn-review"]).toBeDefined();
    expect(out.report.entries).toContainEqual(
      expect.objectContaining({
        path: "skills[review]",
        outcome: "advisory",
        reason: expect.stringMatching(/scripts.*sandbox/),
      }),
    );
  });

  it("has no scripts caveat where the agent has a sandbox", () => {
    const out = adapter.compile(
      input(
        {
          skills: [skill],
          agents: {
            reviewer: {
              template: "eve:blank",
              target: "vercel",
              path: "agents/reviewer",
              env: {},
            },
          },
        },
        {
          texts: {
            "team/skills/review/SKILL.md": withDescription,
            "team/skills/review/scripts/lint.sh": "echo",
          },
        },
      ),
    );
    expect(out.report.entries.some((e) => e.path === "skills[review]")).toBe(
      false,
    );
  });

  it("drops a skill without a description, with the reason", () => {
    for (const text of ["No frontmatter", "---\nname: review\n---\nBody"]) {
      const out = adapter.compile(
        input(
          { skills: [skill] },
          { texts: { "team/skills/review/SKILL.md": text } },
        ),
      );
      expect(out.files["agent/skills/donn-review"]).toBeUndefined();
      expect(out.report.entries).toContainEqual({
        path: "skills[review]",
        outcome: "dropped",
        reason: expect.stringContaining("description"),
      });
    }
  });

  it("accepts a block-scalar description", () => {
    const out = adapter.compile(
      input(
        { skills: [skill] },
        {
          texts: {
            "team/skills/review/SKILL.md":
              "---\ndescription: >-\n  Reviews code\n---\n",
          },
        },
      ),
    );
    expect(out.files["agent/skills/donn-review"]).toBeDefined();
  });

  it("drops a registry skill and a name eve rejects", () => {
    const out = adapter.compile(
      input({
        skills: [
          { name: "remote", source: "registry://org/skills/remote@^1" },
          { name: "a".repeat(60), source: "team/skills/long" },
        ],
      }),
    );
    expect(Object.keys(out.files).filter((f) => f.includes("skills"))).toEqual(
      [],
    );
    expect(out.report.entries.map((e) => [e.path, e.outcome])).toEqual(
      expect.arrayContaining([
        ["skills[remote]", "dropped"],
        [`skills[${"a".repeat(60)}]`, "dropped"],
      ]),
    );
  });
});

describe("names and collisions", () => {
  it("refuses two servers that map to one name, naming both", () => {
    const run = () =>
      adapter.compile(
        input({ mcp: { servers: { my_db: server, "My-DB": server } } }),
      );
    expect(run).toThrow(/name-collision/);
    expect(run).toThrow(/my_db/);
    expect(run).toThrow(/My-DB/);
  });

  it("drops a url server whose name eve cannot take", () => {
    const out = adapter.compile(
      input({ mcp: { servers: { ["a".repeat(60)]: server } } }),
    );
    expect(out.report.entries).toContainEqual({
      path: `mcp.servers.${"a".repeat(60)}`,
      outcome: "dropped",
      reason: expect.stringContaining("name-unmappable"),
    });
  });

  const skillIr = {
    skills: [{ name: "x", source: "team/skills/x" }],
    mcp: { servers: { x: server } },
  };
  it.each([
    ["a template skill file", "agent/skills/donn-x.md"],
    ["a template skill directory", "agent/skills/donn-x/SKILL.md"],
    ["a connection file", "agent/connections/donn-x.ts"],
    ["a connection .mts file", "agent/connections/donn-x.mts"],
    ["a connection .js file", "agent/connections/donn-x.js"],
    ["a connection directory", "agent/connections/donn-x/index.ts"],
    ["a file under lib/donn", "agent/lib/donn/other.ts"],
    ["a tool in the connection's namespace", "agent/tools/donn-x__search.ts"],
    ["a subagent in the namespace", "agent/subagents/donn-x__helper/agent.ts"],
  ])("refuses %s", (_name, existing) => {
    const run = () =>
      adapter.compile(
        input(skillIr, {
          project: { hasSandbox: false, existing: [existing] },
        }),
      );
    expect(run).toThrow(/slot-collision/);
    expect(run).toThrow(existing);
  });

  it("refuses a template instructions/donn.md when the persona has text", () => {
    expect(() =>
      adapter.compile(
        input(
          {},
          {
            project: {
              hasSandbox: false,
              existing: ["agent/instructions/donn.md"],
            },
          },
        ),
      ),
    ).toThrow(/slot-collision/);
  });

  it("ignores template files that do not touch donn names", () => {
    const out = adapter.compile(
      input(skillIr, {
        project: {
          hasSandbox: false,
          existing: [
            "agent/skills/donn-y.md",
            "agent/connections/other.ts",
            "agent/instructions/a.md",
            "agent/tools/donn-xy__t.ts",
          ],
        },
      }),
    );
    expect(out.files["agent/skills/donn-x"]).toBeDefined();
  });
});
